"""MCI loan instance, Step 2: the raw Home Credit files, extracted, counted and hashed.

The competition archive (`kaggle competitions download -c home-credit-default-risk -p data/raw`) is treated as
untrusted input: every member name is checked before anything is written (a plain `*.csv` file name, no folder, no
absolute path), and the CSVs go into their own folder, data/raw/home-credit/. Nothing in data/ is executed or
imported. Only the standard library is used, so the script runs isolated (`python -I`).

For the archive and each CSV: size, SHA-256; for each CSV also the header's column count and the number of records
after the header (csv.reader over the bytes decoded as latin-1, which maps every byte, so quoted line breaks are
counted correctly whatever the file's encoding).

Outputs: results/mci_loan/data/raw-manifest.json and docs/mci/01-data.md (generated from it).

Usage (from the repo root):  .venv/Scripts/python -I scenarios/mci_loan/data_manifest.py
"""
from __future__ import annotations

import csv
import datetime as dt
import hashlib
import json
import os
import platform
import re
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw"
ARCHIVE = RAW / "home-credit-default-risk.zip"
CSV_DIR = RAW / "home-credit"
OUT = ROOT / "results" / "mci_loan" / "data" / "raw-manifest.json"
DOC = ROOT / "docs" / "mci" / "01-data.md"
SAFE_NAME = re.compile(r"^[A-Za-z0-9_.-]+\.csv$")
CHUNK = 1 << 20


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while b := f.read(CHUNK):
            h.update(b)
    return h.hexdigest()


def extract(archive: Path, dest: Path) -> list[str]:
    """Extracts the archive's CSVs into dest after checking every member name; returns the names."""
    with zipfile.ZipFile(archive) as z:
        members = z.infolist()
        bad = [m.filename for m in members if m.is_dir() or not SAFE_NAME.match(m.filename)]
        if bad:
            sys.exit(f"refusing to extract: unexpected member names {bad}")
        dest.mkdir(parents=True, exist_ok=True)
        for m in members:
            target = dest / m.filename
            if target.exists() and target.stat().st_size == m.file_size:
                continue  # already extracted (resume)
            with z.open(m) as src, open(target, "wb") as dst:
                while b := src.read(CHUNK):
                    dst.write(b)
        return sorted(m.filename for m in members)


def count(path: Path) -> tuple[int, int]:
    """(columns in the header, records after the header)."""
    with open(path, encoding="latin-1", newline="") as f:
        rd = csv.reader(f)
        header = next(rd)
        return len(header), sum(1 for _ in rd)


def kaggle_version() -> str:
    exe = Path(sys.executable).with_name("kaggle.exe" if os.name == "nt" else "kaggle")
    try:
        return subprocess.run([str(exe), "--version"], capture_output=True, text=True, timeout=60).stdout.strip()
    except OSError:
        return "not found"


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def write_doc(m: dict) -> None:
    lines = ["# MCI loan instance: Step 2, the raw data", "",
             f"Generated by `scenarios/mci_loan/data_manifest.py` from `{rel(OUT)}`; do not edit by hand.", "",
             "## Source", "",
             "- Kaggle competition `home-credit-default-risk` (Home Credit Default Risk), downloaded with "
             f"`kaggle competitions download -c home-credit-default-risk -p data/raw` ({m['tools']['kaggle']}), "
             "with the student's legacy API key (`~/.kaggle/kaggle.json`, readable by the student's account only).",
             f"- Archive `{m['archive']['file']}`: {m['archive']['bytes']:,} bytes, SHA-256 `{m['archive']['sha256']}`.",
             f"- Extracted into `{m['csvDir']}` (git-ignored, as all of `data/`). Recorded {m['recorded']}.",
             "- The organisations of the MCI instance are simulated: the scenario assigns roles over this one public dataset.",
             "", "## Files", "",
             "Rows are the records after the header line. Every figure below is from "
             f"`{rel(OUT)}`.", "",
             "| File | Bytes | Columns | Rows | SHA-256 |", "|---|---:|---:|---:|---|"]
    for f in m["files"]:
        lines.append(f"| `{f['file']}` | {f['bytes']:,} | {f['columns']:,} | {f['rows']:,} | `{f['sha256']}` |")
    lines += ["", f"{len(m['files'])} CSV files, {sum(f['bytes'] for f in m['files']):,} bytes in all.", "",
              "## Machine", "", f"{m['machine']['platform']}; Python {m['machine']['python']}.", ""]
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    if not ARCHIVE.exists():
        sys.exit(f"{rel(ARCHIVE)} not found: run the kaggle download first")
    names = extract(ARCHIVE, CSV_DIR)
    files = []
    for n in names:
        p = CSV_DIR / n
        cols, rows = count(p)
        files.append({"file": n, "bytes": p.stat().st_size, "columns": cols, "rows": rows, "sha256": sha256(p)})
        print(json.dumps(files[-1]))
    m = {
        "what": "the raw Home Credit Default Risk files (Kaggle competition home-credit-default-risk)",
        "script": "scenarios/mci_loan/data_manifest.py",
        "recorded": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "archive": {"file": rel(ARCHIVE), "bytes": ARCHIVE.stat().st_size, "sha256": sha256(ARCHIVE)},
        "csvDir": rel(CSV_DIR),
        "rowRule": "records after the header line (csv.reader, bytes decoded as latin-1)",
        "files": files,
        "tools": {"kaggle": kaggle_version()},
        "machine": {"platform": platform.platform(), "python": sys.version.split()[0]},
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(m, indent=1) + "\n", encoding="utf-8", newline="\n")  # *.json eol=lf
    write_doc(m)
    print(json.dumps({"files": len(files), "out": rel(OUT), "doc": rel(DOC)}))


if __name__ == "__main__":
    main()
