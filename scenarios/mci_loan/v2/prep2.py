"""MCI loan instance v2: the prepared inputs, in v1's format (scenarios/mci_loan/prep.py; loader offchain/prepared.mjs).

v1's rows, split, label, encodings, neutral fill and extra pool, unchanged; only the owners change (rule2.py):
- MCI (active): its 8 columns (results/mci_loan/v2/select_mci.json), encoded as v1 encoded the Bank's (prep.encode_bank:
  missing values to the training median, standardized on the training rows, times 2^12, rounded, clipped to int16).
- Passives in proposal order Bank, E-commerce company, Credit bureau (manifest `passiveOrder`): rule2.PASSIVE_COLUMNS
  from features.py, encoded as v1 (prep.encode_passives).
- The cohort, split and smoke positions are checked against v1's manifest (results/mci_loan/prepared/manifest.json).

Outputs: data/mci_loan/v2/prepared/ and prepared-smoke/ (git-ignored); copies of the JSON and README under
results/mci_loan/v2/.

Usage (from the repo root):  .venv/Scripts/python -I scenarios/mci_loan/v2/prep2.py
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE.parent), str(HERE)]
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

import common as cm  # noqa: E402
import common2 as c2  # noqa: E402
import features  # noqa: E402
import party_rule as pr  # noqa: E402
import prep  # noqa: E402
import rule2  # noqa: E402


def readme(m: dict, extra_m: dict) -> str:
    nm = c2.names()
    L = ["# MCI loan instance v2: prepared inputs", "", "Generated by `scenarios/mci_loan/v2/prep2.py`; do not edit by hand.", "",
         f"- Rows: {m['rows']:,} applicants (SK_ID_CURR order); training {len(m['split']['train_pos']):,}, test "
         f"{len(m['split']['test_pos']):,}.",
         f"- Classes (repaid / default): training {m['class_counts']['train'][0]:,} / {m['class_counts']['train'][1]:,}; test "
         f"{m['class_counts']['test'][0]:,} / {m['class_counts']['test'][1]:,}.",
         f"- thin_file (no bureau record): {len(m['thin_file_pos']):,} rows.",
         f"- Population default rate of application_train (reweighting, PD prior): {m['population']['default_rate']:.6f} "
         f"({m['population']['defaults']:,} of {m['population']['rows']:,}).", "",
         "## MCI (active): 8 columns, int16 at 2^12", "",
         "| Column | Kind | Missing (train / test) | Training mean | Training SD | Clipped (train / test) |", "|---|---|---:|---:|---:|---:|"]
    for c in m["a"]["vars"]:
        i = m["a"]["info"][c]
        L.append(f"| {c} | {i['kind']} | {i['missing_train']} / {i['missing_test']} | {i['train_mean']:.4f} | {i['train_sd']:.4f} | "
                 f"{i['clipped_train']} / {i['clipped_test']} |")
    L += ["", "## Passives (proposal order)", "", "| Member | Columns |", "|---|---:|"]
    L += [f"| {nm[p]} | {len(m['parties'][p])} |" for p in m["passiveOrder"]]
    L += ["", f"Total width {m['passive']['width']}; dropped as constant on the training rows: "
          f"{', '.join(d['name'] for d in m['passive']['dropped']) or 'none'}.", "",
          "## No record (applicants with no row in the table)", "", "| Member | Table | Rows with no record |", "|---|---|---:|"]
    for t, n in m["no_record"]["by_table"].items():
        L.append(f"| {nm[rule2.TABLES[t]]} | {t} | {n:,} |")
    L += [f"| {nm[p]} | any of its tables | {n:,} |" for p, n in m["no_record"]["by_member"].items()]
    L += ["", f"Extra pool: {extra_m['rows']:,} applicants outside the cohort, passive columns only "
          f"(`{extra_m['passive']['file']}`, SHA-256 `{extra_m['passive']['sha256']}`).",
          "", f"Files: `a_int16.bin` SHA-256 `{m['a']['sha256']}`; `passive_f32.bin` SHA-256 `{m['passive']['sha256']}`.", ""]
    return "\n".join(L)


def main() -> None:
    t0 = time.time()
    app = pd.read_csv(cm.RAW / "application_train.csv").set_index("SK_ID_CURR", drop=False)
    all_ids = app.index.to_numpy()
    target = app["TARGET"].to_numpy()
    cohort = cm.draw_cohort(all_ids, target)
    pool = cm.draw_extra_pool(all_ids, cohort)
    app_c = app.loc[cohort]
    y = app_c["TARGET"].to_numpy()
    train_pos, test_pos = cm.split_positions(cohort, y)
    smoke = cm.smoke_positions(cohort, y, train_pos, test_pos)
    v1p, v1sp = cm.RESULTS / "prepared" / "manifest.json", cm.RESULTS / "prepared-smoke" / "manifest.json"
    if v1p.exists() and v1sp.exists():  # delivery: v1's manifests (row-level) are not delivered; the check runs when present
        v1 = json.loads(v1p.read_text(encoding="utf-8"))
        v1s = json.loads(v1sp.read_text(encoding="utf-8"))
        assert v1["ids"] == cohort.tolist() and v1["split"]["train_pos"] == train_pos.tolist() and v1["split"]["test_pos"] == test_pos.tolist()
        assert v1s["smoke"]["cohort_pos"] == smoke.tolist(), "the cohort, split or smoke sample differs from v1's"
    sel = json.loads((c2.RESULTS2 / "select_mci.json").read_text(encoding="utf-8"))["selected"]
    assert len(sel) == rule2.MCI_N_COLUMNS

    A, a_info = prep.encode_bank(app_c, y, train_pos, test_pos, sel, raw_fn=rule2.raw_candidates, kind_fn=rule2.kind_of)
    F = features.passive_frame(app.loc[np.concatenate([cohort, pool])])[[c["name"] for c in rule2.PASSIVE_COLUMNS]]
    P_all, kept, dropped = prep.encode_passives(F, train_pos, passives=rule2.PASSIVES, columns=rule2.PASSIVE_COLUMNS)
    P, P_extra = P_all[:len(cohort)], P_all[len(cohort):]
    parties = {p: [c["col"] for c in kept if c["owner"] == p] for p in rule2.PASSIVES}
    Fc = F.iloc[:len(cohort)]
    by_table = {t: int((Fc[h] == 0).sum()) for t, h in rule2.HAS_RECORD.items()}
    by_member = {p: int(np.all([Fc[rule2.HAS_RECORD[t]] == 0 for t, o in rule2.TABLES.items() if o == p], axis=0).sum())
                 for p in rule2.PASSIVES}
    thin = np.flatnonzero(Fc["BUR_HAS_RECORD"].to_numpy() == 0)
    common = {
        "version": "v2: MCI active (the student's correction, 2026-10-19)",
        "passiveOrder": rule2.PASSIVES,
        "variables": {p: [c["name"] for c in kept if c["owner"] == p] for p in rule2.PASSIVES},
        "population": {"rows": int(len(target)), "defaults": int(target.sum()), "default_rate": float(target.mean())},
        "cohort": {"seed": cm.COHORT_SEED, "n": cm.N_COHORT, "defaults": cm.N_DEFAULT, "repaid": cm.N_REPAID},
        "seeds": {"cohort": cm.COHORT_SEED, "split": cm.SPLIT_SEED, "extra": cm.EXTRA_SEED, "smoke": cm.SMOKE_SEED,
                  "folds": cm.FOLD_SEED, "calibration": c2.CALIB_SEED},
        "label": {"0": "repaid (TARGET 0)", "1": "default: payment difficulties (TARGET 1), read as on MCI-issued credit"},
        "slots": c2.slots(),
    }

    def extra_fields(rows):
        return {"a": {"vars": sel, "scale": prep.SCALE, "info": a_info, "owner": "mci"}, "passive": {"dropped": dropped},
                "parties": parties, "thin_file_pos": [int(p) for p in rows], **common}

    full = prep.write_set(c2.PREPARED2, c2.RESULTS2 / "prepared", A, P, cohort, y, train_pos, test_pos,
                          {**extra_fields(thin), "no_record": {"by_table": by_table, "by_member": by_member},
                           "ext_source_missing": {c: int(Fc[f"{c}_HAS_VALUE"].eq(0).sum()) for c in pr.EXT_SOURCES}})
    (c2.PREPARED2 / "passive_extra_f32.bin").write_bytes(P_extra.tobytes())
    extra_m = {"rows": int(len(pool)), "ids": [int(i) for i in pool], "seed": cm.EXTRA_SEED, "passiveOrder": rule2.PASSIVES,
               "parties": parties,
               "rule": "the first 2,531 applicants of application_train outside the cohort in SHA-256 order (common.draw_extra_pool)",
               "passive": {"width": int(P_extra.shape[1]), "file": "passive_extra_f32.bin", "dtype": "float32 little-endian",
                           "shape": list(P_extra.shape), "sha256": cm.sha256_file(c2.PREPARED2 / "passive_extra_f32.bin")}}
    for folder in (c2.PREPARED2, c2.RESULTS2 / "prepared"):
        cm.write_json(folder / "extra_manifest.json", extra_m)
        cm.write_json(folder / "columns.json", {"kept": kept, "dropped": dropped}, indent=0)
        (folder / "README.md").write_text(readme(full, extra_m), encoding="utf-8", newline="\n")

    at = {int(p): k for k, p in enumerate(smoke)}
    s_train = np.asarray([at[int(p)] for p in train_pos if int(p) in at])
    s_test = np.asarray([at[int(p)] for p in test_pos if int(p) in at])
    s_thin = np.asarray([at[int(p)] for p in thin if int(p) in at], dtype=int)
    sm = prep.write_set(c2.PREPARED2_SMOKE, c2.RESULTS2 / "prepared-smoke", A[smoke], P[smoke], cohort[smoke], y[smoke], s_train,
                        s_test, {**extra_fields(s_thin), "smoke": {"of": "data/mci_loan/v2/prepared", "cohort_pos": [int(p) for p in smoke],
                                                                   "rule": "common.smoke_positions: 400 + 400 training, 100 + 100 test rows"}})
    for folder in (c2.PREPARED2_SMOKE, c2.RESULTS2 / "prepared-smoke"):
        cm.write_json(folder / "columns.json", {"kept": kept, "dropped": dropped}, indent=0)
    for f in ("prepared/manifest.json", "prepared/extra_manifest.json", "prepared-smoke/manifest.json"):
        c2.redact_manifest(c2.RESULTS2 / f)  # delivery: only the copies under data/ keep the row-level lists
    print(json.dumps({"rows": full["rows"], "mci": sel, "widths": {p: len(v) for p, v in parties.items()},
                      "dropped": [d["name"] for d in dropped], "thin_file": len(thin), "no_record": by_member,
                      "mci_clipped": {c: i["clipped_train"] + i["clipped_test"] for c, i in a_info.items()},
                      "smoke_rows": sm["rows"], "seconds": round(time.time() - t0, 1), "freeRamMB": cm.free_ram_mb()}))


if __name__ == "__main__":
    main()
